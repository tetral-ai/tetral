// Slog groups retain the vocabulary of their scalar leaves after flattening.
func approvedDiagnosticField(key string) bool {
	if approvedDiagnosticFields[key] {
		return true
	}
	for n := 0; n < len(key); n++ {
		if key[n] == '.' && approvedDiagnosticFields[key[n+1:]] {
			return true
		}
	}
	return false
}
